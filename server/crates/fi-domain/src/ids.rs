//! Opaque identifiers (UUIDv7: time-ordered, so B-tree indexes stay append-mostly, ADR 0004 §5).
//!
//! Each id is its own type so an account id can never be passed where a profile id is expected.
//! The nil UUID is refused everywhere: it is what a forgotten field deserializes to.

use serde::{Deserialize, Serialize};
use std::fmt;
use std::str::FromStr;
use uuid::Uuid;

macro_rules! id_type {
    ($(#[$doc:meta])* $name:ident) => {
        $(#[$doc])*
        #[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
        #[serde(try_from = "Uuid", into = "Uuid")]
        pub struct $name(Uuid);

        impl $name {
            /// A new time-ordered id.
            pub fn new() -> Self {
                Self(Uuid::now_v7())
            }

            /// Wraps an existing UUID; `None` for the nil UUID.
            pub fn from_uuid(value: Uuid) -> Option<Self> {
                (!value.is_nil()).then_some(Self(value))
            }

            /// The underlying UUID.
            pub const fn as_uuid(&self) -> Uuid {
                self.0
            }
        }

        impl Default for $name {
            fn default() -> Self {
                Self::new()
            }
        }

        impl TryFrom<Uuid> for $name {
            type Error = NilId;

            fn try_from(value: Uuid) -> Result<Self, NilId> {
                Self::from_uuid(value).ok_or(NilId)
            }
        }

        impl From<$name> for Uuid {
            fn from(value: $name) -> Uuid {
                value.0
            }
        }

        impl FromStr for $name {
            type Err = NilId;

            fn from_str(s: &str) -> Result<Self, NilId> {
                Uuid::parse_str(s).ok().and_then(Self::from_uuid).ok_or(NilId)
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                self.0.hyphenated().fmt(f)
            }
        }
    };
}

/// A nil or malformed UUID where an id was required.
#[derive(Clone, Copy, Debug, PartialEq, Eq, thiserror::Error)]
#[error("a non-nil UUID is required")]
pub struct NilId;

id_type!(
    /// A person's account: the site-key credential, entitlements, devices (ACCOUNTS.md §2).
    AccountId
);
id_type!(
    /// One game profile of an account (an FH2 career with its own XUID and gamertag).
    ProfileId
);
id_type!(
    /// One launcher install on one PC (generated by the launcher on first run).
    DeviceId
);
id_type!(
    /// One launched game session: holds the profile's save lease and the pool slot.
    /// Generated by the launcher so a retried create is idempotent (SAVES_API.md §3).
    PlaySessionId
);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nil_ids_are_refused() {
        assert_eq!(AccountId::from_uuid(Uuid::nil()), None);
        assert!(
            "00000000-0000-0000-0000-000000000000"
                .parse::<ProfileId>()
                .is_err()
        );
        assert!(
            serde_json::from_str::<DeviceId>("\"00000000-0000-0000-0000-000000000000\"").is_err()
        );
    }

    #[test]
    fn ids_round_trip_as_hyphenated_strings() {
        let id = PlaySessionId::new();
        let text = id.to_string();
        assert_eq!(text.len(), 36);
        assert_eq!(text.parse::<PlaySessionId>().unwrap(), id);
        let json = serde_json::to_string(&id).unwrap();
        assert_eq!(json, format!("\"{text}\""));
        assert_eq!(serde_json::from_str::<PlaySessionId>(&json).unwrap(), id);
    }

    #[test]
    fn new_ids_are_time_ordered() {
        let a = ProfileId::new();
        let b = ProfileId::new();
        assert!(a < b, "UUIDv7 ids sort by creation time");
    }
}
