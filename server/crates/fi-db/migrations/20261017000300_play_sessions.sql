-- ForzaInfinity schema, part 3 of 5: pools and play sessions (ADR 0008, ACCOUNTS.md §7).
--
-- A pool is a set of game-plane deployments with its own capacity and admission queue; VIP and
-- free are separate pools, so free load can never take a VIP slot. A play session is one launched
-- game: it is admitted to a pool (or queues), holds the profile's save lease, and keeps both alive
-- with the launcher's heartbeat. Admission is decided in Postgres, so it holds across every
-- instance (Beta kept slots and the queue in one process's memory).
--
-- Admission is one transaction (ADR 0008 §2), with a fixed lock order: the pool first, as the
-- transaction-scoped advisory lock fi_db::sessions::lock_pool takes (pg_advisory_xact_lock on the
-- pool's name: no UPDATE grant on `pool` needed, released at commit or rollback), then the
-- profile's save_head row (fi_db::saves::acquire_in), then the play_session row and the outbox
-- row. A rollback anywhere leaves no lease and no session. The session's fencing token lives only
-- in save_head (lease_session_id = play_session.id): a heartbeat that re-grants it changes nothing
-- here.

CREATE TABLE pool (
  name          text PRIMARY KEY CHECK (name ~ '^[a-z][a-z0-9-]{1,30}$'),
  tier          text NOT NULL CHECK (tier IN ('free', 'vip')),
  -- Concurrent active sessions; NULL is unlimited (the VIP pool scales with Cloud Run instead).
  -- legacy-free (the Beta VM) has 50: the account plane is its only admission (MIGRATION.md §6).
  capacity      integer CHECK (capacity IS NULL OR capacity > 0),
  -- Longest queue; beyond it a launch is refused as full (Beta MAX_LINE).
  queue_limit   integer NOT NULL DEFAULT 20000 CHECK (queue_limit >= 0),
  -- Base URL the hook sends game traffic to (handed to the launcher with the ticket).
  game_endpoint text NOT NULL CHECK (game_endpoint ~ '^https?://[^/]+'),
  accepting     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
  row_version   bigint NOT NULL DEFAULT 1
);

CREATE TRIGGER pool_touch BEFORE UPDATE ON pool FOR EACH ROW EXECUTE FUNCTION fi_touch_row();

CREATE TABLE play_session (
  -- Generated by the launcher, so a retried create is idempotent; also the save lease's session.
  id                uuid PRIMARY KEY,
  account_id        uuid NOT NULL REFERENCES account (id),
  profile_id        uuid NOT NULL REFERENCES profile (id),
  device_binding_id uuid NOT NULL REFERENCES device_binding (id),
  pool              text NOT NULL REFERENCES pool (name),
  state             text NOT NULL CHECK (state IN ('queued', 'active', 'ended', 'expired', 'revoked')),
  launcher_version  text NOT NULL CHECK (char_length(launcher_version) BETWEEN 1 AND 64),
  hook_version      text CHECK (char_length(hook_version) <= 64),
  game_build        text CHECK (char_length(game_build) <= 64),
  car_db_sha256     bytea CHECK (car_db_sha256 IS NULL OR length(car_db_sha256) = 32),
  created_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
  queued_at         timestamptz,
  admitted_at       timestamptz,
  last_heartbeat_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  -- Queued: last poll + 90 s (Beta STALE). Active: last heartbeat + lease TTL.
  expires_at        timestamptz NOT NULL,
  -- Absolute end of an admitted session: admitted_at + 12 h (ACCOUNTS.md §7). Past it heartbeats
  -- are refused (SESSIONS.ENDED, reason max_age) and the launcher re-admits through POST /sessions,
  -- which re-reads the tier: no session keeps a pool by heartbeats alone.
  max_until         timestamptz,
  -- Until when the game plane serves the session (session tokens' exp never passes it): max_until,
  -- or for a VIP session whose access ended, min(access end + 2 h, max_until); now for revoked_* and
  -- suspended. Re-evaluated at every heartbeat; past it, heartbeats keep the save lease (so the
  -- launcher still commits the final save) but mint no game-plane token.
  game_until        timestamptz,
  ended_at          timestamptz,
  end_reason        text CHECK (end_reason IN ('game_exit', 'player', 'takeover', 'expired', 'revoked', 'queue_left', 'max_age')),
  start_revision    bigint CHECK (start_revision >= 0),
  end_revision      bigint CHECK (end_revision >= 0),
  CONSTRAINT play_session_active_shape CHECK (state <> 'active' OR (admitted_at IS NOT NULL AND max_until IS NOT NULL AND game_until IS NOT NULL)),
  CONSTRAINT play_session_game_within_max CHECK (game_until IS NULL OR game_until <= max_until),
  CONSTRAINT play_session_queued_shape CHECK (state <> 'queued' OR queued_at IS NOT NULL),
  CONSTRAINT play_session_closed_shape CHECK ((state IN ('ended', 'expired', 'revoked')) = (ended_at IS NOT NULL AND end_reason IS NOT NULL))
);

-- One live session per profile (the save lease enforces the same; this keeps the two in step).
-- A session past expires_at is moved to 'expired' by the transaction that admits its successor.
CREATE UNIQUE INDEX play_session_one_live_per_profile ON play_session (profile_id) WHERE state IN ('queued', 'active');
CREATE INDEX play_session_live_by_account ON play_session (account_id) WHERE state IN ('queued', 'active');
CREATE INDEX play_session_queue ON play_session (pool, queued_at) WHERE state = 'queued';
CREATE INDEX play_session_active_by_pool ON play_session (pool, expires_at) WHERE state = 'active';
CREATE INDEX play_session_profile_history ON play_session (profile_id, created_at);

-- fi_runtime reads pools; admission serializes on the advisory lock, never on a row lock of `pool`.
GRANT SELECT ON pool TO fi_runtime;
GRANT SELECT, INSERT, UPDATE ON pool TO fi_maintenance;
GRANT SELECT, INSERT, UPDATE ON play_session TO fi_runtime;
GRANT SELECT, UPDATE ON play_session TO fi_maintenance;
